-- ArcheOn Design Studio — Initial Baseline Schema
-- V1: Create baseline tables with IF NOT EXISTS for fresh installations and idempotent execution

-- 1. Users
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255)
);

-- 2. Manifesto
CREATE TABLE IF NOT EXISTS manifesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    headline TEXT,
    paragraphs_json TEXT
);

-- 3. Projects
CREATE TABLE IF NOT EXISTS projects (
    id VARCHAR(255) PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    release_date VARCHAR(255),
    temperature INTEGER,
    summary_title VARCHAR(255),
    summary TEXT,
    tags_json TEXT,
    links_json TEXT,
    socials_json TEXT,
    accent_color VARCHAR(255)
);

-- 4. Leads
CREATE TABLE IF NOT EXISTS leads (
    id UUID PRIMARY KEY,
    client_name VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    service_discipline VARCHAR(255) NOT NULL,
    location VARCHAR(255),
    budget_band VARCHAR(255),
    estimated_timeline VARCHAR(255),
    project_brief VARCHAR(2000),
    whatsapp_opt_in BOOLEAN NOT NULL DEFAULT false,
    opt_in_timestamp TIMESTAMP,
    status VARCHAR(255) DEFAULT 'NEW_ENQUIRY',
    created_at TIMESTAMP
);

-- 5. Audit Events
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id VARCHAR(255) NOT NULL,
    actor_role VARCHAR(255) NOT NULL,
    action VARCHAR(255) NOT NULL,
    entity_name VARCHAR(255) NOT NULL,
    entity_id VARCHAR(255) NOT NULL,
    details_json TEXT,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. Bill Approvals
CREATE TABLE IF NOT EXISTS bill_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id VARCHAR(255) NOT NULL UNIQUE,
    invoice_number VARCHAR(255),
    bill_type VARCHAR(255) DEFAULT 'VENDOR_TO_STUDIO',
    amount NUMERIC(15, 2) NOT NULL,
    paid_amount NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    disputed BOOLEAN NOT NULL DEFAULT false,
    dispute_reason VARCHAR(255),
    payment_proof_url VARCHAR(255),
    payment_proof_utr VARCHAR(255),
    currency VARCHAR(255) NOT NULL,
    vendor_id VARCHAR(255) NOT NULL,
    project_id VARCHAR(255) NOT NULL,
    initiator_id VARCHAR(255) NOT NULL,
    primary_approver_id VARCHAR(255),
    primary_approved_at TIMESTAMP,
    secondary_approver_id VARCHAR(255),
    secondary_approved_at TIMESTAMP,
    status VARCHAR(255) NOT NULL,
    rejection_reason VARCHAR(255),
    is_high_value BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

-- 7. Cash Settlement Requests
CREATE TABLE IF NOT EXISTS cash_settlement_requests (
    id UUID PRIMARY KEY,
    settlement_ref VARCHAR(255) NOT NULL,
    bill_id VARCHAR(255) NOT NULL,
    project_id VARCHAR(255) NOT NULL,
    initiator_id VARCHAR(255) NOT NULL,
    counterparty_id VARCHAR(255) NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(255) NOT NULL DEFAULT 'INR',
    site_purpose VARCHAR(255),
    receipt_reference VARCHAR(255),
    counterparty_status VARCHAR(255) NOT NULL,
    counterparty_responded_at TIMESTAMP,
    counterparty_notes VARCHAR(255),
    finance_approval_status VARCHAR(255) NOT NULL,
    finance_approver_id VARCHAR(255),
    finance_approved_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. Payment Transactions
CREATE TABLE IF NOT EXISTS payment_transactions (
    id UUID PRIMARY KEY,
    bill_id VARCHAR(255) NOT NULL,
    payer_id VARCHAR(255) NOT NULL,
    payee_id VARCHAR(255) NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(255) NOT NULL DEFAULT 'INR',
    payment_mode VARCHAR(255) NOT NULL,
    transaction_reference VARCHAR(255),
    payment_date TIMESTAMP,
    proof_attachment_url VARCHAR(255),
    settlement_status VARCHAR(255) NOT NULL,
    verified_by VARCHAR(255),
    verified_at TIMESTAMP,
    verification_notes VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
