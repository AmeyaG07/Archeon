export type VendorTranslationKey = keyof typeof vendorTranslations.en;

interface VendorLanguageContextValue {
  lang: VendorLanguage;
  setLang: (lang: VendorLanguage) => void;
  t: (key: VendorTranslationKey) => string;
}

const VendorLanguageContext = createContext<VendorLanguageContextValue>({
  lang: "en",
  setLang: () => {},
  t: (key) => vendorTranslations.en[key],
});

export function VendorLanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<VendorLanguage>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as VendorLanguage | null;
      if (saved === "en" || saved === "hi" || saved === "mr") {
        setLangState(saved);
      }
    } catch {
      // Ignore storage errors
    }
  }, []);

  const setLang = useCallback((nextLang: VendorLanguage) => {
    setLangState(nextLang);
    try {
      localStorage.setItem(STORAGE_KEY, nextLang);
    } catch {
      // Ignore storage errors
    }
  }, []);

  const t = useCallback(
    (key: VendorTranslationKey): string => {
      return vendorTranslations[lang][key] ?? vendorTranslations.en[key];
    },
    [lang]
  );

  return (
    <VendorLanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </VendorLanguageContext.Provider>
  );
}

export function useVendorLanguage() {
  return useContext(VendorLanguageContext);
}
